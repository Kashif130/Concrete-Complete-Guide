export function fill(text: string, vars?: Record<string, string | number>): string {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`));
}

/** `v("key", { var })` → string in the active locale, English fallback. */
export function useVT() {
  const { locale } = useLocale();
  return useCallback(
    (key: VKey, vars?: Record<string, string | number>) => fill(dicts[locale][key] ?? en[key], vars),
    [locale],
  );
}
